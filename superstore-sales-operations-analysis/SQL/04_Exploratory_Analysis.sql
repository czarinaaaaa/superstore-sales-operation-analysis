ORDER BY avg_shipdays DESC;

-- Profit Margin by Category
SELECT
    Category,
    SUM(Profit) AS total_profit,
    SUM(Sales) AS total_sales,
    CAST(ROUND((SUM(Profit) / SUM(Sales)) * 100, 2) AS VARCHAR(10)) + '%' AS profit_margin_percent
FROM Superstore_Clean
GROUP BY Category
ORDER BY profit_margin_percent DESC;


