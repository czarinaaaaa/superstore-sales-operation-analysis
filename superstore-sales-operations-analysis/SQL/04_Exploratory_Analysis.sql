-- Explore all Columns in the Database
SELECT *
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'Superstore_Clean';


-- ====================================== --
--			Dimension Exploration		  --
-- ====================================== --

-- Explore all Cities our customers came from 
SELECT DISTINCT 
	City,
	COUNT(DISTINCT Customer_ID) AS Total_Customers
FROM Superstore_Clean
GROUP BY City
ORDER BY Total_Customers DESC;



-- Explore all Categories "The Major Divisions"
SELECT DISTINCT 
	Category, 
	Sub_Category, 
	Product_Name
FROM Superstore_Clean
ORDER BY 1, 2, 3;



-- ====================================== --
--				Date Exploration		  --
-- ====================================== --

-- Find the date of the first and last order 
-- How many years of sales are available
SELECT 
	MIN(Order_Date) AS first_order_date,
	MAX(Order_Date) AS last_order_date,
	DATEDIFF(year, MIN(Order_Date), MAX(Order_Date)) AS analysis_period_years, 
	DATEDIFF(month, MIN(Order_Date), MAX(Order_Date)) AS analysis_period_months
FROM Superstore_Clean;


