-- ====================================== --
--			Ranking Analysis			  --
-- ====================================== --

-- Which 5 Products generate the highest revenue?

SELECT TOP 5 
	Sub_Category, 
	SUM(Sales) AS total_revenue
FROM Superstore_Clean
GROUP BY Sub_Category
ORDER BY total_revenue DESC


SELECT * FROM (
	SELECT 
		Product_Name, 
		Category,
		Price,
		SUM(Sales) AS total_revenue,
		SUM(Quantity) AS total_quantity,
		ROW_NUMBER() OVER (ORDER BY SUM(Sales) DESC) AS rank_products
	FROM Superstore_Clean
	GROUP BY Product_Name,
			 Category,
			 Price) AS ranked_products
WHERE rank_products <= 5

-- What are the 5 worst - performng products in terms of sales?
SELECT TOP 5 
	Product_Name,
	Category,
	Price,
	SUM(Quantity) AS total_quantity,
	SUM(Sales) AS total_revenue
FROM Superstore_Clean
GROUP BY Product_Name,
		 Category,
		 Price
ORDER BY total_revenue

-- Find the TOP 10 Customers who have generated the highest revenue
SELECT TOP 10
	Customer_ID,
	Customer_Name,
	COUNT(DISTINCT Order_ID) as total_orders,
	SUM(Quantity) as total_quantity,
	SUM(Sales) AS total_revenue
FROM Superstore_Clean
GROUP BY Customer_ID, 
		 Customer_Name
ORDER BY total_revenue DESC 

-- The 3 customers with the fewest orders placed
SELECT TOP 3
	Customer_ID,
	Customer_Name, 
	SUM(Quantity) AS total_quantity,
	SUM(Sales) AS total_sales,
	COUNT(DISTINCT Order_ID) AS total_orders
FROM Superstore_Clean
GROUP BY Customer_ID, 
		 Customer_Name
ORDER BY total_orders


-- ====================================== --
--			Relationship Analysis		  --
-- ====================================== --

-- Does higher discounts reduce profits?
SELECT 
	Discount, 
	AVG(Profit) AS avg_profit,
	SUM(Sales) As total_sales
FROM Superstore_Clean
GROUP BY Discount
ORDER BY Discount DESC;

-- Average Discount by Category
SELECT
	Category,
	AVG(Discount) AS avg_discount
FROM Superstore_Clean
GROUP BY Category
ORDER BY avg_discount DESC;
	
-- Profit by Category
SELECT 
	Category,
	SUM(Profit) AS total_profit,
	SUM(Sales) AS total_sales,
	CAST(ROUND((SUM(Profit) * 1.0 / SUM(Sales)) * 100, 2) AS VARCHAR(10)) + '%' AS profit_margin_percentage,
	CAST(ROUND((SUM(Sales) * 1.0 / (SELECT SUM(Sales) FROM Superstore_Clean)) * 100, 2) AS VARCHAR(10)) + '%' AS revenue_share_percentage
FROM Superstore_Clean
GROUP BY Category
ORDER BY total_profit DESC;

-- Average Profit by Region
SELECT 
	Region,
	AVG(Profit) AS avg_profit
FROM Superstore_Clean
GROUP BY Region
ORDER BY avg_profit DESC;

-- Average Shipping Days by Ship Mode
SELECT
	Ship_Mode,
	AVG(Shipping_Days) AS avg_shipdays
FROM Superstore_Clean
GROUP BY Ship_Mode
ORDER BY avg_shipdays;

-- Average Sales by Segment 
